import { spawnSync } from "node:child_process";
import fs from "node:fs/promises";
import path from "node:path";
import { PassThrough } from "node:stream";
import { afterEach, describe, expect, it, vi } from "vitest";
import { useAutoCleanupTempDirTracker } from "../../test/helpers/temp-dir.js";
import {
  buildLaunchAgentEnvironmentWrapper,
  isGeneratedLaunchAgentEnvironmentWrapper,
  resolveLaunchAgentEnvFilePath,
  resolveLaunchAgentEnvWrapperPath,
  writeLaunchAgentPlist,
} from "./launchd-service-files.js";

vi.mock("./launchd-system.js", () => ({ assertNoSystemLaunchDaemonOwnership: vi.fn() }));
const dirs = useAutoCleanupTempDirTracker(afterEach);
const header = "# Generated by OpenClaw. Do not edit while the gateway service is installed.";

describe("LaunchAgent optional Node signing policy", () => {
  it("keeps unguarded behavior and gates command execution with a quoted requirement", async () => {
    const dir = dirs.make("openclaw-signing space-");
    const envFile = path.join(dir, "gateway.env");
    const policy = path.join(dir, "gateway.node-signing-requirement");
    const wrapper = path.join(dir, "wrapper.sh");
    const verifier = path.join(dir, "fake codesign");
    const target = path.join(dir, "fake node");
    await fs.writeFile(envFile, `${header}\nexport TEST_VALUE='preserved value'\n`);
    await fs.writeFile(target, '#!/bin/sh\nprintf "%s|%s" "$TEST_VALUE" "$1"\n', { mode: 0o700 });
    // Linux control-flow fixture only; native macOS tests verify actual signatures.
    await fs.writeFile(
      verifier,
      '#!/bin/sh\n[ "$1" = --verify ] && [ "$2" = --strict ] && [ "$3" = -R ] && [ "$4" = "=official signed node" ] && [ "$5" = "$APPROVED_TEST_TARGET" ]\n',
      { mode: 0o700 },
    );
    const generated = buildLaunchAgentEnvironmentWrapper();
    expect(generated).toContain(
      '/usr/bin/codesign --verify --strict -R "=$signing_requirement" "$1"',
    );
    await fs.writeFile(wrapper, generated.replace("/usr/bin/codesign", `"${verifier}"`));
    const run = (command = target) =>
      spawnSync("/bin/sh", [wrapper, envFile, command, "argument with spaces"], {
        encoding: "utf8",
        env: { ...process.env, APPROVED_TEST_TARGET: target },
      });
    expect(run()).toMatchObject({ status: 0, stdout: "preserved value|argument with spaces" });
    await fs.writeFile(policy, "official signed node\n");
    expect(run()).toMatchObject({ status: 0, stdout: "preserved value|argument with spaces" });
    for (const requirement of ["different team", "ad-hoc", "not node", ""]) {
      await fs.writeFile(policy, requirement);
      expect(run()).toMatchObject({ status: 78, stdout: "" });
    }
    await fs.writeFile(policy, "official signed node");
    expect(run("/bin/true")).toMatchObject({ status: 78, stdout: "" });
    expect(run("node")).toMatchObject({ status: 78, stdout: "" });
    expect(isGeneratedLaunchAgentEnvironmentWrapper(generated)).toBe(true);
    const previous = generated.replace(/invalid_node_identity\(\) \{[\s\S]*?\nfi\n/, "");
    expect(isGeneratedLaunchAgentEnvironmentWrapper(previous)).toBe(true);
  });

  it("preserves the operator policy across real installer regeneration even with empty env", async () => {
    const home = dirs.make("openclaw-signing-install-");
    const env = { HOME: home, OPENCLAW_STATE_DIR: path.join(home, ".openclaw") };
    const envFile = resolveLaunchAgentEnvFilePath(env, "ai.openclaw.gateway");
    const policy = envFile.replace(/\.env$/, ".node-signing-requirement");
    await fs.mkdir(path.dirname(policy), { recursive: true });
    await fs.writeFile(policy, "operator policy\n", { mode: 0o600 });
    const stdout = new PassThrough();
    const args = {
      env,
      stdout,
      programArguments: ["/approved/node", "--max-old-space-size=131072", "/gateway.js"],
    };
    for (const environment of [{ NODE_OPTIONS: "--no-warnings" }, {}]) {
      const { plistPath } = await writeLaunchAgentPlist({ ...args, environment });
      expect(await fs.readFile(envFile, "utf8")).toBe(
        `${header}\n${environment.NODE_OPTIONS ? "export NODE_OPTIONS='--no-warnings'\n" : ""}`,
      );
      expect(await fs.readFile(policy, "utf8")).toBe("operator policy\n");
      expect((await fs.stat(policy)).mode & 0o777).toBe(0o600);
      expect(
        await fs.readFile(resolveLaunchAgentEnvWrapperPath(env, "ai.openclaw.gateway"), "utf8"),
      ).toBe(buildLaunchAgentEnvironmentWrapper());
      expect(await fs.readFile(plistPath, "utf8")).toContain("gateway-env-wrapper.sh");
      expect(await fs.readFile(plistPath, "utf8")).toContain("--max-old-space-size=131072");
    }
  });
});
